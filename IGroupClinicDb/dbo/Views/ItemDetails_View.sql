        d.[Generic name] AS GenericName, d.[Route of Administration] AS RouteOfAdministration, a.GTIN, a.Price_Cash, d.[Trade name], d.[Public price]
FROM    dbo.ItemDetails AS a 
LEFT OUTER JOIN dbo.DrugList AS d 
ON a.GTIN = d.GTIN
