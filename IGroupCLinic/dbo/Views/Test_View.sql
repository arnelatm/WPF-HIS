
CREATE VIEW dbo.Test_View
AS

SELECT b.BranchID,
	b.Trans_Key,
	b.BillType,
	b.TransNbr,
	b.TransType,
	b.TransDateEnglish,
	b.RegistrationNo,
	c.RegistrationDate,
	c.PatientType as RegistrationTYpe,
	case when c.PatientNameEnglish is null then 'Cash Customer' else c.PatientNameEnglish end as PatientNameEnglish,
	b.DoctorID,
	d.EmpNameEnglish as DoctorNameEnglish,
	b.InsuranceID,
	b.InsuranceNameEnglish,
	b.InsuranceGroupID,
	e.NameEnglish as InsuranceTPA,
	b.ExtraDiscountPercent,
	b.ExtraDiscountAmt,
	b.RoundOffAmt,
	b.Reject,
	i.UnderInsuranceID,
	case when b.TransType = 'CA' then b.ExtraDiscountAmt else 0 end as CashExtraDiscount,
    case when b.TransType = 'CR' then b.ExtraDiscountAmt else 0 end as CreditExtraDiscount,
	case when b.TransType = 'CA' then b.RoundOffAmt else 0 end as CashRoundOffAmt,
	case when b.TransType = 'CR' then b.RoundOffAmt else 0 end as CreditRoundOffAmt,
	sum(case when h.DepartmentGroupID = '001' then a.Qty * a.Saleprice else 0 end) as GrossCON,
	sum(case when h.DepartmentGroupID = '002' or h.DepartmentGroupID is null then a.Qty * a.Saleprice else 0 end) as GrossMCT,
	sum(case when h.DepartmentGroupID = '003' then a.Qty * a.SalePrice else 0 end) as GrossXRY,
	sum(case when h.DepartmentGroupID = '004' then a.Qty * a.SalePrice else 0 end) as GrossLAB,
	sum(case when h.DepartmentGroupID = '005' then a.Qty * a.SalePrice else 0 end) as GrossDNT,
	sum(case when h.DepartmentGroupID = '006' then a.Qty * a.SalePrice else 0 end) as GrossOPH,
	sum(case when h.DepartmentGroupID = '007' then a.Qty * a.SalePrice else 0 end) as GrossCMD,
	sum(case when h.DepartmentGroupID = '008' then a.Qty * a.SalePrice else 0 end) as GrossPHR,
	sum(case when h.departmentGroupID = '001' then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscCON,
	sum(case when h.departmentGroupID = '002' OR H.DepartmentGroupID is null then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscMCT,
	sum(case when h.departmentGroupID = '003' then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscXRY,
	sum(case when h.departmentGroupID = '004' then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscLAB,
    sum(case when h.departmentGroupID = '005' then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscDNT,
	sum(case when h.departmentGroupID = '006' then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscOPH,
	sum(case when h.departmentGroupID = '007' then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscCMD,
	sum(case when h.departmentGroupID = '008' then case when a.DiscountAmt = 0 then (a.qty*a.Saleprice*a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscPHR,
	sum(case when h.departmentGroupID <> '008' then a.DeductibleAmt else 0 end) as CLNdedAmt,
	sum(case when h.DepartmentGroupID = '008' then a.DeductibleAmt else 0 end) as PHRdedAmt,
	'Clinic' as InvoiceType 
from ClinicInvoiceDetails a
left outer join ClinicInvoiceGroup b on a.group_key = b.Trans_Key
left outer join patientdetails c on b.RegistrationNo = c.RegistrationNo and b.RegistrationType = c.PatientType
left outer join EmployeeDetails d on b.DoctorID =d.EmpID
left outer join InsuranceDetails e on e.InsuranceID = b.InsuranceGroupID and e.InsuranceType = 'TPA'
left outer join MedicalServices f on a.ServiceID = f.ServiceID
left outer join InsuranceServicePriceList g on a.ServiceID = g.ServiceID and g.InsuranceID = b.InsuranceGroupID
left outer join MedicalDepartments h on h.DepartmentID = (case when f.ServiceID is null then g.DepartmentID else f.departmentid end)
left outer join InsuranceDetails i on i.InsuranceID = b.InsuranceID and i.InsuranceType <> 'TPA' where (b.Reject<>1) and a.ServiceID <> 'CLN-DED' 
group by
	b.BranchID,
	b.Trans_Key,
	b.BillType,
	b.TransNbr,
	b.TransType,
	b.TransDateEnglish,
	b.RegistrationNo,
	c.RegistrationDate,
	c.PatientType,
	c.PatientNameEnglish,
	b.DoctorID,
	d.EmpNameEnglish,
	b.InsuranceID,
	b.InsuranceNameEnglish,
	b.InsuranceGroupID,
	e.NameEnglish,
	b.ExtraDiscountPercent,
	b.ExtraDiscountAmt,
	b.RoundOffAmt,
	b.Reject,
	a.SaleStatus,
	c.PatientType,
	h.DepartmentGroupID,
	i.underinsuranceid
union all
select b.BranchID,
       b.Trans_Key,
	   b.TransType,
	   b.TransNbr,
	   b.TransType,
	   b.TransDateEnglish,
	   b.RegistrationNo,
	   case when d.RegistrationDate is null then b.TransDateEnglish else d.RegistrationDate end as RegistrationDate,
	   case when d.PatientType is null then 'Cash' else d.PatientType end as RegistrationType,
	   case when d.PatientNameENglish is null then 'Cash Customer' else d.PatientNameENglish end as PatientNameEnglish,
	   b.DoctorID,
	   e.EMpNameEnglish as DoctorNameENglish,
	   b.InsuranceID,
	   c.NameENglish as InsuranceNameEnglish,
	   b.InsuranceGroupID,
	   f.nameenglish as InsuranceTPA,
	   b.ExtraDiscountPercent,
	   b.ExtraDiscountAmt,
	   b.RoundOffamt,
	   case when a.SaleStatus = 'SR' then 1 else 0 end as Reject,
	   h.underinsuranceid,
	   case when b.TransType = 'CA' then b.ExtraDiscountAmt else 0 end as CashExtraDiscount,
	   case when b.TransType = 'CR' then b.ExtraDiscountAmt else 0 end as CreditExtraDiscount,
	   case when b.TransType = 'CA' then b.RoundOffAmt else 0 end as CashRoundOffAmt,
	   case when b.TransType = 'CR' then b.RoundOffAmt else 0 end as CreditRoundOffAmt,
	   sum(case when g.DepartmentGroupID = '001' then a.Qty * a.SalePrice else 0 end) as GrossCON,
	   sum(case when g.DepartmentGroupID = '002' or g.DepartmentGroupID is null then a.Qty * a.SalePrice else 0 end) as GrossMCT,
	   sum(case when g.DepartmentGroupID = '003' then a.Qty * a.SalePrice else 0 end) as GrossXRY,
	   sum(case when g.DepartmentGroupID = '004' then a.Qty * a.SalePrice else 0 end) as GrossLAB,
	   sum(case when g.DepartmentGroupID = '005' then a.Qty * a.SalePrice else 0 end) as GrossDNT,
	   sum(case when g.DepartmentGroupID = '006' then a.Qty * a.SalePrice else 0 end) as GrossOPH,
	   sum(case when g.DepartmentGroupID = '007' then a.Qty * a.SalePrice else 0 end) as GrossCMD,
	   sum(case when g.DepartmentGroupID = '008' then a.Qty * a.SalePrice else 0 end) as GrossPHR,
	   sum(case when g.DepartmentGroupID = '001' then case when A.DiscountAmt = 0 then (a.qty*a.saleprice*a.discountper/100) else a.DiscountAmt end else 0 END) as DiscCON,
	   sum(case when g.DepartmentGroupID = '002' or g.DepartmentGroupID is null then case when  a.DiscountAmt = 0 then (a.qty*a.saleprice * a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscMCT,
	   sum(case when g.DepartmentGroupID = '003' then case when  a.DiscountAmt = 0 then (a.qty*a.saleprice * a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscXRY,
	   sum(case when g.DepartmentGroupID = '004' then case when  a.DiscountAmt = 0 then (a.qty*a.saleprice * a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscLAB,
	   sum(case when g.DepartmentGroupID = '005' then case when  a.DiscountAmt = 0 then (a.qty*a.saleprice * a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscDNT,
	   sum(case when g.DepartmentGroupID = '006' then case when  a.DiscountAmt = 0 then (a.qty*a.saleprice * a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscOPH,
	   sum(case when g.DepartmentGroupID = '007' then case when  a.DiscountAmt = 0 then (a.qty*a.saleprice * a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscCMD,
	   sum(case when g.DepartmentGroupID = '008' then case when  a.DiscountAmt = 0 then (a.qty*a.saleprice * a.DiscountPer/100) else a.DiscountAmt end else 0 end) as DiscPHR,
	   sum(case when g.DepartmentGroupID <> '008' then a.DeductibleAmt else 0 end) as CLNdedAmt,
	   sum(case when g.DepartmentGroupID = '008' then a.DeductibleAmt else 0 end) as PHRdedAmt,
	   'Pharmacy' as InvoiceType
from pharmacyinvoicedetails a
left outer join PharmacyInvoiceGroup b on a.group_key = b.Trans_key
left outer join insurancedetails c on b.insuranceid = c.insuranceid
left outer join patientdetails d on b.RegistrationNo = d.RegistrationNo and upper(left(b.RegistrationType,2))=d.Series
left outer join EmployeeDetails e on b.DoctorID = e.EmpID
left outer join InsuranceDetails f on f.InsuranceID = c.GroupInsuranceID and f.InsuranceType = 'TPA'
left outer join MedicalDepartments g on '008' = g.DepartmentGroupID and g.DepartmentID = 'PHR'
left outer join InsuranceDetails h on h.InsuranceID = b.InsuranceID and h.InsuranceType <> 'TPA'
where (a.SaleStatus is null or a. SaleStatus = '') and a.Item_Code <> 'PHR-DED'
group by b.BranchID,
	b.Trans_Key,
	b.TransType,
	b.TransNbr,
	b.TransType,
	b.TransDateEnglish,
	b.RegistrationNo,
	d.RegistrationDate,
	d.PatientType,
	d.PatientNameEnglish,
	b.DoctorID,
	e.EmpNameEnglish,
	b.InsuranceID,
	c.NameEnglish,
	b.InsuranceGroupID,
	f.NameEnglish,
	b.ExtraDiscountPercent,
	b.ExtraDiscountAmt,
	b.RoundOffAmt,
	a.SaleStatus,
	h.underinsuranceid


